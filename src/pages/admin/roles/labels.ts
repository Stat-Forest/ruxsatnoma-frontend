export function permissionHint(
  permission: { code: string; description?: string | null },
  lang: UiLanguage,
): string {
  if (lang === 'uz_latn' && permission.description) {
    return permission.description;
  }
  const translated = PERMISSION_DESCRIPTIONS[lang]?.[permission.code];
  return translated || permission.description || permission.code;
}
