export function groupTitle(prefix: string, lang: UiLanguage | string): string {
  const map = labels[lang as UiLanguage] ?? labels.uz_latn;
  const known = map.groups as Record<string, string | undefined>;
  return known[prefix] ?? prefix;
}

export function pickRoleName(
  role: { name?: Record<string, unknown> | null; code: string },
  lang: UiLanguage | string,
): string {
  const fromName = pickName(role.name, lang);
  if (fromName && fromName.toLowerCase() !== role.code.toLowerCase()) {
    return fromName;
  }
  const fromCode = translateTerm(role.code, lang);
  return fromCode || role.code;
}

