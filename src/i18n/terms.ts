/**
 * Translates a known database term or fallback name to the desired UI language.
 */
export function translateTerm(value: string | null | undefined, lang: string): string {
  if (!value || typeof value !== 'string') return value ?? '';
  const trimmed = value.trim().toLowerCase();
  let mapping: Record<string, string> | undefined = TERM_TRANSLATIONS[trimmed];
  if (!mapping) {
    const normalized = trimmed.replace(/[ʻ’‘`]/g, "'").replace(/[–—]/g, '-');
    mapping = TERM_TRANSLATIONS[normalized];
  }
  if (!mapping) {
    const simplified = trimmed.replace(/[ʻ’‘`']/g, '').replace(/[–—]/g, '-');
    mapping = Object.entries(TERM_TRANSLATIONS).find(
      ([k]) => k.replace(/[ʻ’‘`']/g, '').replace(/[–—]/g, '-') === simplified,
    )?.[1];
  }
  if (mapping && mapping[lang]) {
    return mapping[lang];
  }
  return value;
}
